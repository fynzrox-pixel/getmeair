param(
    [string]$ConfigDir = $PSScriptRoot,
    [string]$SourceDir = (Join-Path (Split-Path -Parent $ConfigDir) 'source\Telegram\SourceFiles')
)

$ErrorActionPreference = 'Stop'

$apiId = $env:API_ID
$apiHash = $env:API_HASH

$envFile = Join-Path $ConfigDir 'api.env'
if (-not $apiId -and (Test-Path -LiteralPath $envFile)) {
    foreach ($line in [System.IO.File]::ReadAllLines($envFile)) {
        $trimmed = $line.Trim()
        if (-not $trimmed -or $trimmed.StartsWith('#')) { continue }
        $index = $trimmed.IndexOf('=')
        if ($index -lt 1) { continue }
        $key = $trimmed.Substring(0, $index).Trim()
        $value = $trimmed.Substring($index + 1).Trim().Trim('"', "'")
        if ($key -eq 'API_ID' -and -not $apiId) { $apiId = $value }
        if ($key -eq 'API_HASH' -and -not $apiHash) { $apiHash = $value }
    }
}

if (-not $apiId -or -not $apiHash) {
    throw 'Copy config/api.env.example to config/api.env and set API_ID and API_HASH, or export them as environment variables. Get your own credentials at https://my.telegram.org/apps.'
}

if ($apiId -notmatch '^\d+$') {
    throw 'API_ID must be a decimal integer.'
}
if ([int64]$apiId -le 0) {
    throw 'API_ID must be positive.'
}
if ($apiHash -notmatch '^[0-9a-fA-F]{32}$') {
    throw 'API_HASH must be a 32-character hexadecimal string.'
}
if ($apiHash -match '^0{32}$') {
    throw 'API_HASH is still the placeholder from api.env.example.'
}

$target = Join-Path $SourceDir 'core\api_credentials.generated.h'
$content = @(
    '// Generated by Getmeair/config/apply_api.ps1. Do not edit or commit.',
    '#pragma once',
    '',
    'constexpr auto ApiId = ' + $apiId + ';',
    'constexpr auto ApiHash = "' + $apiHash + '";',
    ''
) -join "`r`n"
[System.IO.File]::WriteAllText($target, $content, [System.Text.UTF8Encoding]::new($false))

Write-Output "Wrote $target"
Write-Output 'Credentials are never printed or stored in build logs.'
